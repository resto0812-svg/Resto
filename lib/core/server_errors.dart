    case 'resto.forbidden':
      return t.errorForbidden;
    case 'resto.owner_only':
      return t.errorOwnerOnly;
    case 'resto.rate_limited':
      return t.errorRateLimited;
    case 'resto.invalid_timezone':
      return t.errorInvalidTimezone;
    case 'resto.invalid_role':
