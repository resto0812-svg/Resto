    case 'resto.invitation_invalid':
      return t.errorInvitationInvalid;
    case 'resto.invitation_wrong_account':
      return t.errorInvitationWrongAccount;
    case 'resto.last_owner':
      return t.errorLastOwner;
    case 'resto.membership_revoked':
      return t.errorMembershipRevoked;
